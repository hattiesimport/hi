/* =====================================
   SCROLL REVEAL
===================================== */

function revealElements() {

    const reveals =
        document.querySelectorAll(".reveal");


    reveals.forEach(element => {

        const windowHeight =
            window.innerHeight;


        const elementTop =
            element.getBoundingClientRect().top;


        const revealPoint =
            100;


        if (
            elementTop <
            windowHeight - revealPoint
        ) {

            element.classList.add("active");

        }

    });

}


window.addEventListener(
    "scroll",
    revealElements
);


revealElements();



