/* =====================================
   SEARCH
===================================== */

searchInput.addEventListener("input", () => {

    const searchValue =
        searchInput.value.toLowerCase();


    const filteredProducts =
        products.filter(product =>

            product.name
                .toLowerCase()
                .includes(searchValue)

            ||

            product.category
                .toLowerCase()
                .includes(searchValue)

        );


    displayProducts(filteredProducts);

});



/* =====================================
   ADD TO CART
===================================== */

function addToCart(productId, quantity = 1) {

    const product =
        products.find(
            item => item.id === productId
        );


    const existingProduct =
        cart.find(
            item => item.id === productId
        );


    if (existingProduct) {

        existingProduct.quantity += quantity;

    }

    else {

        cart.push({

            ...product,

            quantity: quantity

        });

    }


    updateCart();


    showToast("Added to cart!");


    animateCart();


}



/* =====================================
   UPDATE CART
===================================== */

function updateCart() {

    const totalItems =
        cart.reduce(

            (total, item) =>
                total + item.quantity,

            0

        );


    cartCount.textContent =
        totalItems;


    cartItems.innerHTML = "";


    let totalPrice = 0;


    if (cart.length === 0) {

        cartItems.innerHTML = `

            <div
                style="
                    text-align:center;
                    padding:50px 10px;
                    color:#777;
                "
            >

                <i
                    class="
                        fa-solid
                        fa-bag-shopping
                    "

                    style="
                        font-size:45px;
                        color:#e75480;
                    "
                ></i>


                <p
                    style="
                        margin-top:15px;
                    "
                >

                    Your cart is empty.

                </p>

            </div>

        `;

    }


    cart.forEach(item => {

        totalPrice +=
            item.price *
            item.quantity;


        cartItems.innerHTML += `

            <div class="cart-item">


                <img
                    src="${item.image}"
                    alt="${item.name}"
                >


                <div class="cart-item-info">


                    <h4>

                        ${item.name}

                    </h4>


                    <p>

                        GH₵${item.price.toFixed(2)}

                    </p>


                    <div class="cart-quantity">


                        <button
                            onclick="
                                changeQuantity(
                                    ${item.id},
                                    -1
                                )
                            "
                        >

                            -

                        </button>


                        <span>

                            ${item.quantity}

                        </span>


                        <button
                            onclick="
                                changeQuantity(
                                    ${item.id},
                                    1
                                )
                            "
                        >

                            +

                        </button>


                        <button
                            class="remove-item"

                            onclick="
                                removeFromCart(
                                    ${item.id}
                                )
                            "
                        >

                            <i
                                class="
                                    fa-solid
                                    fa-trash
                                "
                            ></i>

                        </button>


                    </div>


                </div>


            </div>

        `;

    });


    cartTotal.textContent =
        `GH₵${totalPrice.toFixed(2)}`;

}



/* =====================================
   CHANGE QUANTITY
===================================== */

function changeQuantity(productId, change) {

    const product =
        cart.find(
            item => item.id === productId
        );


    product.quantity += change;


    if (product.quantity <= 0) {

        removeFromCart(productId);

    }


    updateCart();

}



/* =====================================
   REMOVE FROM CART
===================================== */

function removeFromCart(productId) {

    cart =
        cart.filter(
            item => item.id !== productId
        );


    updateCart();


    showToast("Item removed from cart.");

}



