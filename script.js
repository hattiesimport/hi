/* =====================================
   FILTER PRODUCTS
===================================== */

function filterProducts(category) {

    let filteredProducts;


    if (category === "All") {

        filteredProducts = products;

    }

    else {

        filteredProducts =
            products.filter(product =>
                product.category === category
            );

    }


    displayProducts(filteredProducts);


    document
        .getElementById("products")
        .scrollIntoView({

            behavior: "smooth"

        });


}



